		// a trailing comment formats to the same canonical body as the
		// exact bytes it was parsed from, and the stamp and semantic
		// constant both derive from that body.
		root := t.TempDir()
		content := "/* docs */\r\nprocedure echo {\r\n    value string;\r\n} string;\r\n"
		file := importFixture(t, root, "crlf.intercall", content)
