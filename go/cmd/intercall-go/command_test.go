	t.Run("ExportRejectsNoncanonicalOwnedInterface", func(t *testing.T) {
		root := exportFixture(t)
		cliEnv(t, root)
		out := filepath.Join(root, "out")
		intf := filepath.Join(root, "interfaces", "api.intercall")
		args := []string{"export", "--out", out, "--interface", intf, "./prov"}
		if status, _, stderr := runCLI(t, args...); status != 0 {
			t.Fatalf("first export status = %d, stderr = %q", status, stderr)
		}
		// Rewrite the interface target with a valid marker and blank
		// line and a recomputed valid lowercase stamp over a
		// noncanonical variant of the generated body: marker and
		// digest are valid and the digest matches the body, but the
		// body is not the canonical form of a valid interface, so it
		// is not owned (RM-14).
		src := readFile(t, intf)
		body := interfaceBody(t, src)
		noncanonical := bytes.ReplaceAll(body, []byte("    "), []byte("  "))
		if bytes.Equal(noncanonical, body) {
			t.Fatalf("fixture body has no four-space indentation to de-canonicalize:\n%s", body)
		}
		tampered := []byte("/* Code generated by intercall-go; artifact sha256:" + tool.ArtifactStamp(noncanonical) + "; DO NOT EDIT. */\n\n" + string(noncanonical))
		if err := os.WriteFile(intf, tampered, 0o644); err != nil {
			t.Fatal(err)
		}
		bindingPath := filepath.Join(out, "binding_gen.go")
		bindingBefore, err := os.Stat(bindingPath)
		if err != nil {
			t.Fatal(err)
		}
		intfBefore, err := os.Stat(intf)
		if err != nil {
			t.Fatal(err)
		}
		status, _, stderr := runCLI(t, args...)
		if status != 1 || !strings.Contains(stderr, "not replaceable") || !strings.Contains(stderr, "canonical") {
			t.Errorf("noncanonical export: status %d, stderr %q; want the canonicality ownership error", status, stderr)
		}
		if strings.Contains(stderr, ".tmp-") {
			t.Errorf("stderr reports a staging path: %q", stderr)
		}
		bindingAfter, err := os.Stat(bindingPath)
		if err != nil {
			t.Fatal(err)
		}
		intfAfter, err := os.Stat(intf)
		if err != nil {
			t.Fatal(err)
		}
		if !os.SameFile(bindingBefore, bindingAfter) || !os.SameFile(intfBefore, intfAfter) {
			t.Error("a target was replaced or rewritten despite the noncanonical owned interface")
		}
		if got := readFile(t, intf); !bytes.Equal(got, tampered) {
			t.Error("the noncanonical interface bytes changed")
		}
		if got := readFile(t, bindingPath); bindingStamp(t, got) != interfaceStamp(t, src) {
			t.Error("the binding was replaced despite the noncanonical owned interface")
		}
	})

